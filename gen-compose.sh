#!/bin/sh
#
# Generate the per-tunnel parts of the gwtor deployment from ./wg/*.conf:
#
#   compose.override.yaml  one tor-<name> service per WireGuard config,
#                          at 10.185.100.3, .4, ... in config name order
#   run/gwproxy/acl.txt    gwproxy's upstream pool: every SOCKS port of
#                          every Tor instance, balanced by "random two"
#   run/gwproxy/auth.txt   gwproxy's credentials, created only if missing
#
# Usage: ./gen-compose.sh
#
# Environment:
#   GWTOR_SUBNET_PREFIX  first three octets of the gwtor network [10.185.100]
#   GWTOR_FIRST_HOST     last octet of the first Tor container          [3]
#   GWTOR_SOCKS_PORT_LOW   first SOCKS port of every Tor instance  [8000]
#   GWTOR_SOCKS_PORT_HIGH  last SOCKS port of every Tor instance   [8031]
#   GWPROXY_USER         initial gwproxy username                 [gwproxy]
#   GWPROXY_PASS         initial gwproxy password      [e70ed37f7ec082d0aa]

set -eu

cd "$(dirname "$0")"

PREFIX=${GWTOR_SUBNET_PREFIX:-10.185.100}
FIRST_HOST=${GWTOR_FIRST_HOST:-3}
first_port=${GWTOR_SOCKS_PORT_LOW:-8000}
last_port=${GWTOR_SOCKS_PORT_HIGH:-8031}
GWPROXY_USER=${GWPROXY_USER:-gwproxy}
GWPROXY_PASS=${GWPROXY_PASS:-e70ed37f7ec082d0aa}
TOR_IMAGE=gwtor/tor:0.4.9.16
# gwproxy refuses a pool of more than 8192 servers.
MAX_POOL=8192

die() { printf 'gen-compose: error: %s\n' "$*" >&2; exit 1; }

# A port number: digits only, no leading zero, 1-65535.
is_port() {
	case "$1" in
	''|*[!0-9]*|0*) return 1 ;;
	esac
	[ "${#1}" -le 5 ] && [ "$1" -le 65535 ]
}
is_port "$first_port" ||
	die "GWTOR_SOCKS_PORT_LOW=$first_port is not a port number"
is_port "$last_port" ||
	die "GWTOR_SOCKS_PORT_HIGH=$last_port is not a port number"
[ "$first_port" -le "$last_port" ] ||
	die "GWTOR_SOCKS_PORT_LOW is above GWTOR_SOCKS_PORT_HIGH"
nr_ports=$((last_port - first_port + 1))

# Config names become service and volume names.
names=
for f in wg/*.conf; do
	[ -e "$f" ] || continue
	n=$(basename "$f" .conf)
	case "$n" in
	*[!a-z0-9_-]*|'') die "$f: name must be [a-z0-9_-]+" ;;
	esac
	names="$names $n"
done
[ -n "$names" ] || die "no WireGuard configs in wg/"

# shellcheck disable=SC2086 # count the words on purpose
set -- $names
nr=$#
host_last=$((FIRST_HOST + nr - 1))
[ "$host_last" -le 254 ] || die "too many configs for $PREFIX.0/24"
[ $((nr * nr_ports)) -le "$MAX_POOL" ] ||
	die "$nr configs x $nr_ports ports exceeds gwproxy's $MAX_POOL-server pool limit"

umask 077
mkdir -p run/gwproxy

tmp=$(mktemp compose.override.yaml.XXXXXX)
trap 'rm -f "$tmp"' EXIT
{
	echo "# Generated by gen-compose.sh from wg/*.conf; do not edit."
	echo
	echo "services:"
	h=$FIRST_HOST
	for n in $names; do
		cat <<EOF
  tor-$n:
    image: $TOR_IMAGE
    pull_policy: never
    restart: unless-stopped
    hostname: tor-$n
    cap_add: [NET_ADMIN]
    sysctls:
      net.ipv6.conf.all.disable_ipv6: 0
      net.ipv6.conf.default.disable_ipv6: 0
    environment:
      TOR_SOCKS_PORT_LOW: "$first_port"
      TOR_SOCKS_PORT_HIGH: "$last_port"
      TOR_SOCKS_ACCEPT: "$PREFIX.0/24"
    networks:
      gwtor:
        ipv4_address: $PREFIX.$h
    volumes:
      - ./wg/$n.conf:/etc/gwtor/wg.conf:ro
      - tor-$n:/var/lib/tor

EOF
		h=$((h + 1))
	done
	echo "  gwproxy:"
	echo "    user: \"$(id -u):$(id -g)\""
	echo "    depends_on:"
	for n in $names; do
		echo "      - tor-$n"
	done
	echo
	echo "volumes:"
	for n in $names; do
		echo "  tor-$n:"
	done
} > "$tmp"
chmod 0644 "$tmp"
mv "$tmp" compose.override.yaml

# "random two": each connection goes to the less loaded of two ports
# drawn at random, which keeps the open connections nearly as even as
# least_conn at the cost of round-robin.  The servers are interleaved by
# instance anyway, since the pool falls back to the block's order when its
# draws only land on ejected servers.
tmp=$(mktemp run/gwproxy/acl.txt.XXXXXX)
{
	echo "# Generated by gen-compose.sh from wg/*.conf; do not edit."
	echo "upstream tor {"
	echo "    random two;"
	p=$first_port
	while [ "$p" -le "$last_port" ]; do
		h=$FIRST_HOST
		for n in $names; do
			echo "    server socks5h://$PREFIX.$h:$p;"
			h=$((h + 1))
		done
		p=$((p + 1))
	done
	echo "}"
	echo "-P INPUT ACCEPT"
	echo "-A OUTPUT -m domain --domain localhost -j REJECT"
	echo "-A OUTPUT -j UPSTREAM --to tor"
	echo "-P OUTPUT ACCEPT"
} > "$tmp"
mv "$tmp" run/gwproxy/acl.txt

if [ ! -e run/gwproxy/auth.txt ]; then
	printf '%s:%s\n' "$GWPROXY_USER" "$GWPROXY_PASS" > run/gwproxy/auth.txt
	echo "created run/gwproxy/auth.txt with user $GWPROXY_USER"
fi
trap - EXIT

h=$FIRST_HOST
for n in $names; do
	echo "tor-$n: $PREFIX.$h, SOCKS5 ports $first_port-$last_port"
	h=$((h + 1))
done
echo "gwproxy pool: $((nr * nr_ports)) servers"
